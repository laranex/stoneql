export function columnType(draft: ColumnDraft, engine: Engine) {
  if (engine === 'PostgreSQL' && draft.enumValues && draft.enumName === draft.dataType)
    return { name: draft.dataType };
  return columnCapabilities[engine].types.find((t) => t.name === draft.dataType);
}
export function defaultExpressions(draft: ColumnDraft, engine: Engine) {
  return Object.entries(columnCapabilities[engine].expressions)
    .filter(([, types]) => types.includes(draft.dataType))
    .map(([name]) => name);
}
export function createColumnDraft(engine: Engine, column?: Column): ColumnDraft {
  const cap = columnCapabilities[engine],
    base = (column?.type.split('(')[0] ?? 'VARCHAR')
      .replace(/\s+unsigned/i, '')
      .trim()
      .toUpperCase();
  let dataType = base;
  if (!cap.types.some((t) => t.name === dataType))
    dataType =
      engine === 'SQLite'
        ? /int/i.test(base)
          ? 'INTEGER'
          : /decimal|numeric/i.test(base)
            ? 'NUMERIC'
            : 'TEXT'
        : base === 'DATETIME'
          ? 'TIMESTAMP'
          : 'VARCHAR';
  if (engine === 'PostgreSQL' && column?.enumValues) dataType = column.enumName || column.type;
  const args = column?.type.match(/\((.*)\)/)?.[1] ?? '';
  const expressions = cap.expressions;
  return {
    name: column?.name ?? '',
    enumName: column?.enumName,
    enumValues: column?.enumValues ? [...column.enumValues] : undefined,
    dataType,
    length: Number(args) || 255,
    precision: Number(args.split(',')[0]) || 10,
    scale: Number(args.split(',')[1]) || 0,
    values: /^(ENUM|SET)$/.test(base) ? args : '',
    nullable: column?.nullable ?? true,
    unsigned: cap.unsigned && !!(column?.unsigned || /\bunsigned\b/i.test(column?.type ?? '')),
    autoIncrement:
      column?.autoIncrement ??
      !!(column?.primary && cap.types.find((t) => t.name === dataType)?.integer),
    collation: column?.collation ?? '',
    comment: column?.comment ?? '',
    key: column?.primary
      ? 'primary'
      : column?.unique
        ? 'unique'
        : column?.indexed
          ? 'index'
          : 'none',
    defaultKind:
      column?.defaultKind ??
      (column?.default !== undefined
        ? expressions[column.default]
          ? 'expression'
          : 'custom'
        : 'none'),
    defaultValue: column?.default ?? '',
    expression:
      column?.default && expressions[column.default]
        ? column.default
        : (Object.keys(expressions).find((name) => expressions[name]!.includes(dataType)) ?? ''),
    position: column ? 'keep' : 'end',
    after: '',
  };
}
export function formatColumnType(d: ColumnDraft, engine: Engine): string {
  const spec = columnType(d, engine);
  let type = d.dataType.toLowerCase();
  if (spec?.parameters === 'length') type += `(${d.length})`;
  if (spec?.parameters === 'decimal') type += `(${d.precision},${d.scale})`;
  if (spec?.parameters === 'values')
    type += `(${parseValues(d.values)
      .map((v) => `'${v.replaceAll("'", "''")}'`)
      .join(',')})`;
  if (d.unsigned) type += ' unsigned';
  return type;
}
export function validateColumn(
  d: ColumnDraft,
  engine: Engine,
  table: Table,
  original = '',
): string[] {
  const cap = columnCapabilities[engine],
    spec = columnType(d, engine),
    errors: string[] = [];
  if (!/^[A-Za-z_]\w*$/.test(d.name))
    errors.push(
      'Column name must start with a letter or underscore and contain only letters, numbers, and underscores.',
    );
  if (
    table.columns.some((c) => c.name !== original && c.name.toLowerCase() === d.name.toLowerCase())
  )
    errors.push('A column with this name already exists.');
  if (!spec) errors.push('Choose a supported data type.');
  if (
    spec?.parameters === 'length' &&
    (!Number.isInteger(d.length) ||
      d.length < 1 ||
      d.length > (d.dataType === 'CHAR' && cap.unsigned ? 255 : cap.maxLength))
  )
    errors.push('Enter a valid positive character length within the engine limit.');
  if (
    spec?.parameters === 'decimal' &&
    (!Number.isInteger(d.precision) ||
      d.precision < 1 ||
      d.precision > cap.maxPrecision ||
      !Number.isInteger(d.scale) ||
      d.scale < 0 ||
      d.scale > Math.min(d.precision, cap.maxScale))
  )
    errors.push(
      `DECIMAL precision must be 1–${cap.maxPrecision}, and scale 0–${Math.min(d.precision, cap.maxScale)}.`,
    );
  let choices: string[] = [];
  if (spec?.parameters === 'values')
    try {
      choices = parseValues(d.values);
      if (d.dataType === 'SET' && (choices.length > 64 || choices.some((v) => v.includes(','))))
        errors.push('SET supports at most 64 values without commas.');
    } catch (e) {
      errors.push((e as Error).message);
    }
  if (d.unsigned && (!cap.unsigned || !spec?.numeric))
    errors.push('UNSIGNED is not supported for this type or engine.');
  if (
    d.key === 'primary' &&
    (d.nullable || (table.columns.some((c) => c.name !== original && c.primary) && !table.indexes?.some(i=>i.kind==='primary'&&i.columns.length>1&&i.columns.some(p=>p.column===original))))
  )
    errors.push(
      'A primary key must be NOT NULL. Manage composite primary keys in the Indexes section.',
    );
  if (
    d.autoIncrement &&
    (!spec?.integer ||
      d.nullable ||
      (engine !== 'PostgreSQL' && !['primary', 'unique', 'index'].includes(d.key)) ||
      (engine === 'SQLite' && (d.dataType !== 'INTEGER' || d.key !== 'primary')))
  )
    errors.push(
      `${cap.autoLabel} requires a non-null indexed integer${engine === 'SQLite' ? ' primary key' : ''}.`,
    );
  if (
    d.autoIncrement &&
    table.columns.some((c) => c.name !== original && (c.autoIncrement ?? c.primary))
  )
    errors.push('Only one generated increment column is supported per table.');
  if (d.autoIncrement && d.defaultKind !== 'none')
    errors.push('Generated increment columns cannot have an explicit default.');
  if (d.defaultKind === 'null' && !d.nullable) errors.push('A NULL default requires Allow NULL.');
  if (d.defaultKind === 'expression' && !defaultExpressions(d, engine).includes(d.expression))
    errors.push('Choose an expression supported by this type and engine.');
  if (d.defaultKind === 'custom') {
    if (
      spec?.numeric &&
      (!d.defaultValue.trim() ||
        !Number.isFinite(Number(d.defaultValue)) ||
        (spec.integer && !Number.isInteger(Number(d.defaultValue))))
    )
      errors.push('The custom default must be a valid number for this type.');
    if (d.unsigned && Number(d.defaultValue) < 0)
      errors.push('An UNSIGNED default cannot be negative.');
    if (spec?.parameters === 'length' && d.defaultValue.length > d.length)
      errors.push('The default exceeds the character length.');
    if (d.dataType === 'ENUM' && choices.length && !choices.includes(d.defaultValue))
      errors.push('The default must be an ENUM value.');
    if (
      d.dataType === 'SET' &&
      choices.length &&
      d.defaultValue.split(',').some((v) => !choices.includes(v))
    )
      errors.push('The default must contain only selected SET values.');
  }
  if (d.collation && (!spec?.text || !cap.collations.includes(d.collation)))
    errors.push('Choose a collation supported by this character type and engine.');
  if (d.comment && !cap.comments) errors.push('Column comments are not supported by this engine.');
  if (!cap.positioning && ['first', 'after'].includes(d.position))
    errors.push('Physical column positioning is not supported by this engine.');
  if (
    d.position === 'after' &&
    !table.columns.some((c) => c.name !== original && c.name === d.after)
  )
    errors.push('Choose an existing different column for AFTER.');
  if (original && !table.columns.some((c) => c.name === original))
    errors.push('The original column no longer exists.');
  if (!original && table.rows.length && !d.nullable && d.defaultKind === 'none' && !d.autoIncrement)
    errors.push('A new NOT NULL column needs a default for existing mock records.');
  return errors;
}
export function applyColumnDefinition(
  table: Table,
  d: ColumnDraft,
  engine: Engine,
  original = '',
): Column {
  if(table.kind && table.kind!=='table') throw new Error('Views are read-only in this prototype.');
  const errors = validateColumn(d, engine, table, original);
  if (errors.length) throw new Error(errors.join(' '));
  const old = table.columns.find((c) => c.name === original),
    spec = columnType(d, engine)!;
  const column: Column = {
    ...old,
    name: d.name,
    type: formatColumnType(d, engine),
    nullable: d.nullable,
    primary: d.key === 'primary',
    unique: d.key === 'unique',
    indexed: d.key === 'index',
    unsigned: d.unsigned,
    autoIncrement: d.autoIncrement,
    collation: d.collation || undefined,
    comment: d.comment || undefined,
    enumName: d.dataType === d.enumName ? d.enumName : undefined,
    enumValues: d.dataType === d.enumName ? d.enumValues : undefined,
    defaultKind: d.defaultKind,
    default:
      d.defaultKind === 'custom'
        ? d.defaultValue
        : d.defaultKind === 'expression'
          ? d.expression
          : undefined,
  };
  const values = table.rows.map((row, i) => {
    let value: Row[string] = original
      ? (row[original] ?? null)
      : d.autoIncrement
        ? i + 1
        : d.defaultKind === 'custom'
          ? d.defaultValue
          : d.defaultKind === 'expression'
            ? expressionValue(d.expression)
            : null;
    if (value === null && !d.nullable)
      throw new Error('Existing NULL values conflict with NOT NULL.');
    if (value !== null && spec.numeric) {
      if (
        String(value).trim() === '' ||
        !Number.isFinite(Number(value)) ||
        (spec.integer && !Number.isInteger(Number(value))) ||
        (d.unsigned && Number(value) < 0)
      )
        throw new Error('Existing values are incompatible with the selected numeric type.');
      // Keep the exact original numeric representation; never round through Number.
    }
    if (value !== null && spec.parameters === 'length' && String(value).length > d.length)
      throw new Error('Existing values exceed the new character length.');
    if (value !== null && d.dataType === 'ENUM' && !parseValues(d.values).includes(String(value)))
      throw new Error('Existing values are not in the ENUM list.');
    const checked = validateValue(column, value, engine);
    if (!checked.valid) throw new Error(checked.error);
    return value;
  });
  if (
    (column.primary || column.unique) && !table.indexes?.some(i=>i.kind==='primary'&&i.columns.length>1&&i.columns.some(p=>p.column===original)) &&
    new Set(values.filter((v) => v !== null).map(String)).size !==
      values.filter((v) => v !== null).length
  )
    throw new Error('Existing duplicate values conflict with the selected key.');
  const oldIndex = table.columns.findIndex((c) => c.name === original),
    columns = table.columns.filter((c) => c.name !== original);
  const index =
    d.position === 'first'
      ? 0
      : d.position === 'after'
        ? columns.findIndex((c) => c.name === d.after) + 1
        : original && (d.position === 'keep' || !columnCapabilities[engine].positioning)
          ? oldIndex
          : columns.length;
  columns.splice(index, 0, column);
  const indexes = reconcileColumnIndexes(table,column,original);
  const nextRows = table.rows.map((row,i)=>{const next={...row};if(original&&original!==d.name) delete next[original];next[d.name]=values[i]!;return next;});
  const candidate = {...table,columns,indexes,rows:nextRows};
  for(const index of indexes){const errors=validateIndex(candidate,index,engine,index.name);if(errors.length)throw new Error(errors.join(' '));}
  for(const row of nextRows){const error=rowIndexError(candidate,row,row);if(error) throw new Error(error);}
  table.indexes = indexes;
  table.columns = columns;
  syncIndexFlags(table);
  table.rows.forEach((row, i) => {
    if (original && original !== d.name) delete row[original];
    row[d.name] = values[i]!;
  });
  return column;
}
export function expressionValue(expression: string): string {
  const now = new Date().toISOString();
  return expression === 'CURRENT_DATE'
    ? now.slice(0, 10)
    : expression === 'CURRENT_TIME'
      ? now.slice(11, 19)
      : now.slice(0, 19).replace('T', ' ');
}

export function getColumnCapabilities(engine: Engine, table?: Table) {
  const cap = columnCapabilities[engine];
  const enumNames =
    engine === 'PostgreSQL'
      ? Array.from(
          new Set(
            (table?.columns ?? []).filter((c) => c.enumValues).map((c) => c.enumName || c.type),
          ),
        )
      : [];
  return { ...cap, types: [...cap.types, ...enumNames.map((name) => ({ name }))] };
}
