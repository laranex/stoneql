export type DefaultKind = 'none' | 'null' | 'custom' | 'expression';
export interface ColumnDraft {
  name: string;
  dataType: string;
  length: number;
  precision: number;
  scale: number;
  values: string;
  nullable: boolean;
  unsigned: boolean;
  autoIncrement: boolean;
  collation: string;
  comment: string;
  key: 'none' | 'primary' | 'unique' | 'index';
  defaultKind: DefaultKind;
  defaultValue: string;
  expression: string;
  position: 'keep' | 'first' | 'after' | 'end';
  after: string;
  enumName?: string;
  enumValues?: string[];
}
interface TypeSpec {
  name: string;
  parameters?: 'length' | 'decimal' | 'values';
  numeric?: boolean;
  integer?: boolean;
  text?: boolean;
}
interface ColumnCapabilities {
  types: TypeSpec[];
  positioning: boolean;
  unsigned: boolean;
  comments: boolean;
  autoLabel: string;
  collations: string[];
  maxLength: number;
  maxPrecision: number;
  maxScale: number;
  expressions: Record<string, string[]>;
}
